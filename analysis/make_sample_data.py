"""Generates SYNTHETIC sample results for trying analyze.py before real data exists.

Every file carries "synthetic": true. They are NOT real testers; never report them.
Writes 8 JSON files and codes.txt (2 codes encoded exactly like the game does:
SD1 = raw deflate + base64url).
"""
import base64
import json
import random
import zlib
from pathlib import Path

random.seed(7)
OUT = Path(__file__).parent / "sample-data"
OUT.mkdir(exist_ok=True)

BANK = {
    "A": [("A1", "scam", True), ("A2", "scam", True), ("A3", "scam", False), ("A4", "legit", True), ("A5", "legit", False), ("A6", "legit", False)],
    "B": [("B1", "scam", True), ("B2", "scam", False), ("B3", "scam", False), ("B4", "legit", True), ("B5", "legit", True), ("B6", "legit", False)],
}


def items(form: str, skill: float, other_p: float):
    out = []
    for iid, truth, polished in BANK[form]:
        correct = random.random() < skill
        verdict = truth if correct else ("legit" if truth == "scam" else "scam")
        conf = random.choice([0.5, 0.6, 0.7, 0.8, 0.9, 1.0])
        brier = (conf - (1 if correct else 0)) ** 2
        other = random.random() < other_p
        out.append({"id": iid, "truth": truth, "polished": polished, "verdict": verdict, "confidence": conf, "correct": correct,
                    "brier": round(brier, 4), "firstAction": f"{iid}.act{3 if other else 1}", "otherChannel": other})
    return out


def make(n: int) -> dict:
    code = f"T-{9000 + n}"
    pre_form, post_form = ("A", "B") if n % 2 else ("B", "A")
    return {
        "v": 1, "synthetic": True, "tester": code, "age": random.choice(["13-15", "16-18", "19+"]), "lang": "ar", "gender": "f",
        "startedAt": 1794300000000, "finishedAt": 1794301500000,
        "pre": {"form": pre_form, "items": items(pre_form, 0.62, 0.25)},
        "post": {"form": post_form, "items": items(post_form, 0.78, 0.6)},
        "cases": [], "summary": {"otherChannelCount": 2, "brierCases": 0.12},
        "feedback": {"open": ["synthetic", "synthetic", "synthetic"], "likert": [4, 4, 5, 4, 5]},
    }


def encode(obj: dict) -> str:
    raw = json.dumps(obj, separators=(",", ":")).encode("utf-8")
    comp = zlib.compressobj(wbits=-15)
    packed = comp.compress(raw) + comp.flush()
    return "SD1." + base64.urlsafe_b64encode(packed).decode().rstrip("=")


files = [make(i) for i in range(1, 11)]
for r in files[:8]:
    (OUT / f"results-{r['tester']}.json").write_text(json.dumps(r, ensure_ascii=False, indent=2), encoding="utf-8")
(OUT / "codes.txt").write_text("\n".join(encode(r) for r in files[8:]) + "\n", encoding="utf-8")
(OUT / "README.md").write_text("SYNTHETIC sample data generated by ../make_sample_data.py. Not real testers. Never report these numbers.\n", encoding="utf-8")
print("wrote 8 json + 2 codes")
